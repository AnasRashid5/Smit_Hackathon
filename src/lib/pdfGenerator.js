import { jsPDF } from 'jspdf';

export function generatePayslipPDF(payslip, employee, company, payrollRun) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  
  // Header background banner
  doc.setFillColor(30, 41, 59); // Slate-800
  doc.rect(0, 0, pageWidth, 40, 'F');

  // Company Name
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text(company?.name || 'HCM Lite Company', 14, 20);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text('CONFIDENTIAL SALARY PAYSLIP', 14, 28);
  doc.text(`Period: ${payrollRun.month}/${payrollRun.year}`, pageWidth - 14, 28, { align: 'right' });

  // Reset text color for body
  doc.setTextColor(33, 41, 54);

  // Employee Details Card
  doc.setFillColor(248, 250, 252);
  doc.roundedRect(14, 48, pageWidth - 28, 32, 2, 2, 'F');

  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text('EMPLOYEE DETAILS', 20, 56);
  
  doc.setFont('helvetica', 'normal');
  doc.text(`Name: ${employee.first_name} ${employee.last_name}`, 20, 64);
  doc.text(`Employee Code: ${employee.emp_code}`, 20, 72);
  doc.text(`Email: ${employee.email}`, 110, 64);
  doc.text(`Status: ${employee.status.toUpperCase()}`, 110, 72);

  // Attendance Summary Card
  doc.setFillColor(241, 245, 249);
  doc.roundedRect(14, 85, pageWidth - 28, 22, 2, 2, 'F');

  doc.setFont('helvetica', 'bold');
  doc.text('ATTENDANCE SUMMARY', 20, 93);
  doc.setFont('helvetica', 'normal');
  doc.text(`Working Days: ${payslip.working_days}`, 20, 100);
  doc.text(`Attended Days: ${payslip.attended_days}`, 75, 100);
  doc.text(`Absent / Unpaid: ${payslip.absent_days}`, 130, 100);

  // Earnings & Deductions Breakdown
  const tableY = 115;
  doc.setFillColor(226, 232, 240);
  doc.rect(14, tableY, pageWidth - 28, 8, 'F');

  doc.setFont('helvetica', 'bold');
  doc.text('EARNINGS', 20, tableY + 6);
  doc.text('AMOUNT (PKR)', 75, tableY + 6);
  doc.text('DEDUCTIONS', 110, tableY + 6);
  doc.text('AMOUNT (PKR)', 165, tableY + 6);

  doc.setFont('helvetica', 'normal');
  let rowY = tableY + 16;

  // Earnings Rows
  doc.text('Basic Salary', 20, rowY);
  doc.text(Number(payslip.basic_salary).toLocaleString(), 75, rowY);

  doc.text('Absent / Leave Deductions', 110, rowY);
  doc.text(Number(payslip.leave_deductions).toLocaleString(), 165, rowY);

  rowY += 10;
  doc.text('House Rent Allowance (HRA 40%)', 20, rowY);
  doc.text(Number(payslip.hra).toLocaleString(), 75, rowY);

  doc.text('Income Tax (Annual Slabs / 12)', 110, rowY);
  doc.text(Number(payslip.tax_deduction).toLocaleString(), 165, rowY);

  rowY += 10;
  doc.text('Medical Allowance (10%)', 20, rowY);
  doc.text(Number(payslip.medical).toLocaleString(), 75, rowY);

  rowY += 15;
  // Subtotals
  doc.line(14, rowY - 4, pageWidth - 14, rowY - 4);
  doc.setFont('helvetica', 'bold');
  doc.text('Gross Earnings', 20, rowY);
  doc.text(`PKR ${Number(payslip.gross_salary).toLocaleString()}`, 75, rowY);

  const totalDeductions = Number(payslip.leave_deductions) + Number(payslip.tax_deduction);
  doc.text('Total Deductions', 110, rowY);
  doc.text(`PKR ${totalDeductions.toLocaleString()}`, 165, rowY);

  // Net Pay Highlight Box
  rowY += 18;
  doc.setFillColor(15, 23, 42);
  doc.roundedRect(14, rowY, pageWidth - 28, 22, 3, 3, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(12);
  doc.text('NET SALARY PAYABLE', 20, rowY + 14);
  doc.setFontSize(16);
  doc.text(`PKR ${Number(payslip.net_salary).toLocaleString()}`, pageWidth - 20, rowY + 14, { align: 'right' });

  // Footer notes & Computer Generated disclaimer
  doc.setTextColor(148, 163, 184);
  doc.setFontSize(8);
  doc.text('This document is computer-generated by HCM Lite and does not require a signature.', pageWidth / 2, 280, { align: 'center' });

  // Save / Download PDF
  const filename = `Payslip_${employee.emp_code}_${payrollRun.month}_${payrollRun.year}.pdf`;
  doc.save(filename);
}
